//! Evidence construction utilities
//!
//! Shared utilities for building consistent evidence across all analyzers.

use crate::lexer::Span;

/// A place in a text: its 1-based line, and its 1-based column counted in
/// characters and in UTF-16 code units. Each report gives the column in the
/// unit its format defines.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct TextPosition {
    pub line: usize,
    /// Column in characters (Unicode scalar values).
    pub column: usize,
    /// Column in UTF-16 code units.
    pub utf16_column: usize,
}

impl TextPosition {
    /// The first column of 1-based `line`.
    pub fn line_start(line: usize) -> Self {
        Self {
            line,
            column: 1,
            utf16_column: 1,
        }
    }

    /// Where `text`, written from this place, ends.
    pub fn after(self, text: &str) -> Self {
        let (from, tail) = match text.rfind('\n') {
            Some(newline) => (
                Self::line_start(self.line + text.matches('\n').count()),
                &text[newline + 1..],
            ),
            None => (self, text),
        };
        Self {
            line: from.line,
            column: from.column + tail.chars().count(),
            utf16_column: from.utf16_column + tail.encode_utf16().count(),
        }
    }
}

/// Line offset index for O(log n) line number lookups
///
/// Build once, use many times. Replaces O(n) scanning for each lookup.
#[derive(Debug, Clone)]
pub struct LineIndex {
    /// Byte offsets where each line starts (0-indexed positions)
    line_starts: Vec<usize>,
}

/// Result of resolving a span to line numbers
#[derive(Debug, Clone)]
pub struct ResolvedLineInfo {
    /// Line number in the rendered SQL (always available)
    pub rendered_line: usize,
    /// Line number in the original template (if source map available)
    pub template_line: Option<usize>,
    /// Whether this line was generated by a macro
    pub is_generated: bool,
    /// Name of the macro that generated this line (if applicable)
    pub macro_name: Option<String>,
}

impl ResolvedLineInfo {
    /// Get the best line number to display to the user
    /// Prefers template_line if available, falls back to rendered_line
    pub fn display_line(&self) -> usize {
        self.template_line.unwrap_or(self.rendered_line)
    }
}

impl LineIndex {
    /// Build line index from source (O(n) - do once per file)
    pub fn new(src: &str) -> Self {
        let mut line_starts = vec![0];
        for (i, c) in src.char_indices() {
            if c == '\n' {
                line_starts.push(i + 1);
            }
        }
        Self { line_starts }
    }

    /// Get 1-indexed line number for a span (O(log n) via binary search)
    pub fn get_line_number(&self, span: Span) -> usize {
        let pos = span.start as usize;
        match self.line_starts.binary_search(&pos) {
            Ok(line) => line + 1, // Exact match at line start
            Err(line) => line,    // Between line starts, so in previous line
        }
    }

    /// The place of byte `offset` in `text`, the text this index was built
    /// from: an offset inside a character is the place of that character.
    pub fn position(&self, text: &str, offset: usize) -> TextPosition {
        let mut offset = offset.min(text.len());
        while !text.is_char_boundary(offset) {
            offset -= 1;
        }
        let line = self.line_starts.partition_point(|&start| start <= offset);
        let start = self
            .line_starts
            .get(line.saturating_sub(1))
            .copied()
            .unwrap_or(0);
        TextPosition::line_start(line.max(1)).after(text.get(start..offset).unwrap_or_default())
    }

    /// The byte offset in `text`, the text this index was built from, of
    /// 1-based `line` and `column` in characters, as [`Self::position`]
    /// gives them; `None` past the end of that line.
    pub fn offset_at(&self, text: &str, line: usize, column: usize) -> Option<usize> {
        let start = *self.line_starts.get(line.checked_sub(1)?)?;
        let end = self.line_starts.get(line).copied().unwrap_or(text.len());
        let line_text = text.get(start..end)?;
        let skip = column.checked_sub(1)?;
        line_text
            .char_indices()
            .map(|(at, _)| at)
            .chain(std::iter::once(line_text.len()))
            .nth(skip)
            .map(|at| start + at)
    }

    /// CENTRALIZED LINE RESOLUTION: Resolve a span to full line info including template mapping
    ///
    /// This is THE canonical way to get line numbers for display. It handles:
    /// 1. Converting byte offset (span) to rendered line number
    /// 2. Looking up template line via source map (if available)
    /// 3. Determining if line was macro-generated
    ///
    /// Use `display_line()` on the result to get the best line for user display.
    pub fn resolve_span(
        &self,
        span: Span,
        source_map: Option<&crate::template::SourceMap>,
    ) -> ResolvedLineInfo {
        let rendered_line = self.get_line_number(span);

        let (template_line, is_generated, macro_name) = if let Some(sm) = source_map {
            match sm.get_line_source(rendered_line as u32) {
                Some(crate::template::LineSource::Literal { template_line }) => {
                    (Some(*template_line as usize), false, None)
                }
                Some(crate::template::LineSource::Generated {
                    call_site_line,
                    macro_name,
                }) => (Some(*call_site_line as usize), true, macro_name.clone()),
                Some(crate::template::LineSource::Unknown) | None => (None, false, None),
            }
        } else {
            (None, false, None)
        };

        ResolvedLineInfo {
            rendered_line,
            template_line,
            is_generated,
            macro_name,
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::lexer::Span;

    #[test]
    fn test_line_index() {
        let src = "line 1\nline 2\nline 3";
        let index = LineIndex::new(src);

        // Test line 1 (positions 0-5)
        assert_eq!(index.get_line_number(Span { start: 0, end: 1 }), 1);
        assert_eq!(index.get_line_number(Span { start: 5, end: 6 }), 1);

        // Test line 2 (positions 7-12)
        assert_eq!(index.get_line_number(Span { start: 7, end: 8 }), 2);
        assert_eq!(index.get_line_number(Span { start: 12, end: 13 }), 2);

        // Test line 3 (positions 14+)
        assert_eq!(index.get_line_number(Span { start: 14, end: 15 }), 3);
        assert_eq!(index.get_line_number(Span { start: 19, end: 20 }), 3);
    }

    // A column counts what comes before it on its line in characters and in
    // UTF-16 code units, never in bytes: `ñ` and `€` are one of each, an
    // emoji is one character and two code units.
    #[test]
    fn a_position_counts_characters_and_utf16_units_not_bytes() {
        let src = "select 1;\nselect 'ñ€😀中' , x = null;";
        let index = LineIndex::new(src);
        let at = src.find("x =").expect("x");
        let position = index.position(src, at);
        assert_eq!(
            position,
            TextPosition {
                line: 2,
                column: 17,
                utf16_column: 18
            }
        );
        assert_eq!(index.offset_at(src, 2, 17), Some(at));
        assert_eq!(index.position(src, 0), TextPosition::line_start(1));
        // An offset inside a character is that character's place.
        let euro = src.find('€').expect("euro");
        assert_eq!(index.position(src, euro + 1), index.position(src, euro));
        assert_eq!(index.offset_at(src, 3, 1), None);
    }
}
